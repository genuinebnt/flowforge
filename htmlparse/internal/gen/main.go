// Command gen generates htmlparse/entities_table.go and
// conformance/htmlparse/entities.json from the named character reference
// data in golang.org/x/net/html/entity.go (which is the WHATWG
// "named character references" table, HTML §13.5).
//
// Usage (from the module root; this is what `go generate ./htmlparse`
// runs):
//
//	go run ./htmlparse/internal/gen \
//	    -src "$(go list -m -f '{{.Dir}}' golang.org/x/net)/html/entity.go" \
//	    -go htmlparse/entities_table.go \
//	    -json conformance/htmlparse/entities.json
//
// The source is parsed with go/parser (no code from x/net is imported or
// copied); only the two map literals `entity` and `entity2` are read.
// Output is deterministic: names are sorted bytewise.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
	"unicode/utf8"
)

// entry is one reference: name and one or two code points.
type entry struct {
	name string // without '&', with ';' when the reference has one
	cps  []rune
}

func main() {
	src := flag.String("src", "", "path to golang.org/x/net/html/entity.go")
	goOut := flag.String("go", "htmlparse/entities_table.go", "Go output file")
	jsonOut := flag.String("json", "conformance/htmlparse/entities.json", "JSON output file")
	flag.Parse()
	if *src == "" {
		fmt.Fprintln(os.Stderr, "gen: -src is required")
		os.Exit(2)
	}
	entries, err := load(*src)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*goOut, renderGo(entries), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*jsonOut, renderJSON(entries), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func load(path string) ([]entry, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}
	byName := map[string][]rune{}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, spec := range gd.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, n := range vs.Names {
				if n.Name != "entity" && n.Name != "entity2" {
					continue
				}
				lit, ok := vs.Values[i].(*ast.CompositeLit)
				if !ok {
					return nil, fmt.Errorf("%s is not a composite literal", n.Name)
				}
				for _, elt := range lit.Elts {
					kv := elt.(*ast.KeyValueExpr)
					key, err := strconv.Unquote(kv.Key.(*ast.BasicLit).Value)
					if err != nil {
						return nil, err
					}
					var cps []rune
					switch v := kv.Value.(type) {
					case *ast.BasicLit:
						r, err := runeLit(v)
						if err != nil {
							return nil, err
						}
						cps = []rune{r}
					case *ast.CompositeLit:
						for _, e := range v.Elts {
							r, err := runeLit(e.(*ast.BasicLit))
							if err != nil {
								return nil, err
							}
							cps = append(cps, r)
						}
					default:
						return nil, fmt.Errorf("unexpected value for %q", key)
					}
					// entity2 holds the two-code-point references; it
					// wins over any single-code-point entry.
					if _, dup := byName[key]; !dup || n.Name == "entity2" {
						byName[key] = cps
					}
				}
			}
		}
	}
	if len(byName) == 0 {
		return nil, fmt.Errorf("no entities found in %s", path)
	}
	// Map order does not reach the output: the names are sorted next.
	out := make([]entry, 0, len(byName))
	for k, v := range byName {
		out = append(out, entry{k, v})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, nil
}

func runeLit(b *ast.BasicLit) (rune, error) {
	v, _, _, err := strconv.UnquoteChar(b.Value[1:len(b.Value)-1], '\'')
	return v, err
}

func renderGo(es []entry) []byte {
	var b bytes.Buffer
	maxLen := 0
	for _, e := range es {
		maxLen = max(maxLen, len(e.name))
	}
	b.WriteString("// Code generated by htmlparse/internal/gen from golang.org/x/net/html/entity.go; DO NOT EDIT.\n\n")
	b.WriteString("package htmlparse\n\n")
	fmt.Fprintf(&b, "// entityCount is the number of named character references (HTML §13.5).\nconst entityCount = %d\n\n", len(es))
	fmt.Fprintf(&b, "// entityMaxLen is the length of the longest reference name.\nconst entityMaxLen = %d\n\n", maxLen)
	b.WriteString("// entityNames lists the reference names without the leading '&', sorted\n")
	b.WriteString("// bytewise. Names that end in ';' and the legacy names without it are\n")
	b.WriteString("// separate entries, as in the standard's table.\n")
	b.WriteString("var entityNames = [entityCount]string{\n")
	for _, e := range es {
		fmt.Fprintf(&b, "\t%q,\n", e.name)
	}
	b.WriteString("}\n\n")
	b.WriteString("// entityValues[i] holds the code points of entityNames[i]; the second\n")
	b.WriteString("// is 0 for single-code-point references.\n")
	b.WriteString("var entityValues = [entityCount][2]rune{\n")
	for _, e := range es {
		second := rune(0)
		if len(e.cps) > 1 {
			second = e.cps[1]
		}
		fmt.Fprintf(&b, "\t{0x%X, 0x%X},\n", e.cps[0], second)
	}
	b.WriteString("}\n")
	renderTrie(&b, es)
	return b.Bytes()
}

// renderJSON writes the WHATWG entities.json format
// ({"&name": {"codepoints": [...], "characters": "..."}}), keys sorted,
// one entry per line.
func renderJSON(es []entry) []byte {
	var b bytes.Buffer
	b.WriteString("{\n")
	for i, e := range es {
		key := jsonString("&" + e.name)
		chars := make([]byte, 0, 8)
		cps := make([]byte, 0, 16)
		for j, r := range e.cps {
			chars = utf8.AppendRune(chars, r)
			if j > 0 {
				cps = append(cps, ", "...)
			}
			cps = strconv.AppendInt(cps, int64(r), 10)
		}
		val := jsonString(string(chars))
		fmt.Fprintf(&b, "  %s: { \"codepoints\": [%s], \"characters\": %s }", key, cps, val)
		if i < len(es)-1 {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// jsonString encodes s as a JSON string without HTML escaping.
func jsonString(s string) []byte {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return bytes.TrimRight(b.Bytes(), "\n")
}

// trieNode is a node of the trie while it is built; renderTrie flattens
// it into entityTrieNodes/entityTrieEdges, where a node's children become
// edges[first : first+count] sorted by byte. entity is the index of the
// name that ends here, or -1.
type trieNode struct {
	children map[byte]*trieNode
	entity   int
	id       int
}

// renderTrie emits the compact trie used by the CharRefTrie lookup
// strategy: nodes are numbered breadth-first, each node's outgoing edges
// are contiguous and sorted, so a lookup is one binary (or linear) search
// per input byte.
func renderTrie(b *bytes.Buffer, es []entry) {
	root := &trieNode{children: map[byte]*trieNode{}, entity: -1}
	for i, e := range es {
		n := root
		for j := 0; j < len(e.name); j++ {
			c := e.name[j]
			next, ok := n.children[c]
			if !ok {
				next = &trieNode{children: map[byte]*trieNode{}, entity: -1}
				n.children[c] = next
			}
			n = next
		}
		n.entity = i
	}
	var order []*trieNode
	queue := []*trieNode{root}
	for len(queue) > 0 {
		n := queue[0]
		queue = queue[1:]
		n.id = len(order)
		order = append(order, n)
		keys := sortedKeys(n.children)
		for _, k := range keys {
			queue = append(queue, n.children[k])
		}
	}
	type edge struct {
		c     byte
		child int
	}
	var edges []edge
	firsts := make([]int, len(order))
	for i, n := range order {
		firsts[i] = len(edges)
		for _, k := range sortedKeys(n.children) {
			edges = append(edges, edge{k, n.children[k].id})
		}
	}
	fmt.Fprintf(b, "\n// entityTrieNodes is the prefix trie over entityNames (node 0 is the\n")
	fmt.Fprintf(b, "// root): {first edge, edge count, entity index or -1}.\n")
	fmt.Fprintf(b, "var entityTrieNodes = [%d]entityTrieNode{\n", len(order))
	for i, n := range order {
		fmt.Fprintf(b, "\t{%d, %d, %d},\n", firsts[i], len(n.children), n.entity)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// entityTrieEdges are the trie edges {byte, child node}, grouped by\n// parent and sorted by byte.\n")
	fmt.Fprintf(b, "var entityTrieEdges = [%d]entityTrieEdge{\n", len(edges))
	for _, e := range edges {
		fmt.Fprintf(b, "\t{%q, %d},\n", e.c, e.child)
	}
	b.WriteString("}\n")
}

// sortedKeys returns m's keys in byte order, so the numbering does not
// depend on map iteration.
func sortedKeys(m map[byte]*trieNode) []byte {
	keys := make([]byte, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}
